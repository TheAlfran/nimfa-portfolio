// Turns the resume PDF into sharp images for the website's resume popup.
//
//   bun run resume:images      (runs with Node)
//
// Run this again whenever you replace the PDF in public/. It writes:
//   - public/resume/page-1.webp, page-2.webp, ...   (one image per page)
//   - src/data/resumePages.ts                        (list of pages + sizes, used by the popup)

import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadImage, createCanvas } from '@napi-rs/canvas';
import { definePDFJSModule, getDocumentProxy, renderPageAsImage } from 'unpdf';
import { RESUME_PDF } from '../src/data/portfolioData.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PDF_PATH = path.join(ROOT, 'public', RESUME_PDF.url.replace(/^\//, ''));
const OUT_DIR = path.join(ROOT, 'public', 'resume');
const DATA_FILE = path.join(ROOT, 'src', 'data', 'resumePages.ts');

// 2.5× the PDF's size → sharp on high-resolution screens, still a small file.
const SCALE = 2.5;
const WEBP_QUALITY = 88;

// Use the full pdf.js build (unpdf's default lightweight build can't draw embedded photos)
await definePDFJSModule(() => import('pdfjs-dist/legacy/build/pdf.mjs'));

const pdfBytes = new Uint8Array(await readFile(PDF_PATH));
const pdf = await getDocumentProxy(pdfBytes.slice());

await mkdir(OUT_DIR, { recursive: true });
for (const old of await readdir(OUT_DIR)) {
  if (old.startsWith('page-')) await rm(path.join(OUT_DIR, old));
}

const pages: { src: string; width: number; height: number }[] = [];
const version = Date.now().toString(36); // busts browser caches when the resume changes

for (let n = 1; n <= pdf.numPages; n++) {
  const png = await renderPageAsImage(pdf, n, {
    canvasImport: () => import('@napi-rs/canvas'),
    scale: SCALE,
  });

  // Re-encode as WebP (much smaller than PNG, same sharpness)
  const image = await loadImage(Buffer.from(png));
  const canvas = createCanvas(image.width, image.height);
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, image.width, image.height);
  ctx.drawImage(image, 0, 0);
  const webp = await canvas.encode('webp', WEBP_QUALITY);

  const fileName = `page-${n}.webp`;
  await writeFile(path.join(OUT_DIR, fileName), webp);
  pages.push({ src: `/resume/${fileName}?v=${version}`, width: image.width, height: image.height });
  console.log(`page ${n}: ${image.width}×${image.height}, ${(webp.length / 1024).toFixed(0)} KB`);
}

await writeFile(
  DATA_FILE,
  `// Generated by scripts/render-resume.ts — run \`bun run resume:images\` after replacing the resume PDF.\n` +
    `export const RESUME_PAGES = ${JSON.stringify(pages, null, 2)};\n`,
);
console.log(`Done: ${pages.length} page(s) → public/resume/ and src/data/resumePages.ts`);
